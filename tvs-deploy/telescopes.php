                <a name="make"></a>
                <h2 class="subtitle">Make Your Own Scope</h2>

                <p>
                    If you'd like a little bit of a challenge, you can make your own scope. There
                    are several scope making books out there to help you make one of your own.
                    However, it is easier if you can be involved in a telescope making workshop or
                    class.
                </p>

                <p>
                    One place that you can go is the Telescope Makers' Workshop run through the
                    <a href="http://www.eastbayastro.org" target="_blank">Eastbay Astronomical Society (EAS)</a>.
                    They meet every Friday night at the Chabot Space &amp; Science Center in Oakland.
                    For more information on their program, visit the EAS web site.
                </p>

                <p>
                    In the past, TVS has conducted telescope making workshops for its members.
                    Here's a little blurb our TM (telescope making) leader wrote that will
                    give you an idea of what's involved:
                </p>

                <p>
                    <span style="font-family: Helvetica, Arial, Geneva, SunSans-Regular, sans-serif;">
                        The Tri-Valley Stargazers Telescope Making Workshop<br>
                    </span>
                    by Rich Combs 1996 (thanks Rich!)
                </p>

                <p>
                    The Tri-Valley Stargazers Amateur Telescope Makers Workshop was started in 1991.
                    That year a dozen enthusiastic members of the club met twice a week and spent as
                    long as five months to grind, polish, figure their own mirrors, and assembled
                    them into home made dobsonian mounts.
                </p>

                <p>
                    This first group of ATM's used cement tools with ceramic tiles epoxied on their
                    surface. In the five years since, the techniques have been streamlined a bit, so
                    that this year it takes four months, meeting only one night a week, to complete
                    the mirrors, and a few Saturdays to make the mounts. Over 45 scopes have been made,
                    the largest being 12.5", and most being 6" f/8, which has become the
                    standard beginners scope. A new group meets once a year, usually in the fall,
                    although in 1996 we started in March. There are eight "Grit Pushers" in
                    the current group, and we hope to have the mirrors and mounts completed by the end
                    of June.
                </p>

                <p>
                    Some details of the standard 6" f/8 scopes are as follows. We use pyrex mirror
                    blanks and plate glass tools from Newport Glass in Southern California that are
                    pre-molded, or generated, to an f/8 curve. This allows us to start with #120 abrasive,
                    which is adequate to remove the mold marks. After working through the normal sequence
                    of silicon carbide abrasives, #120, #220, #320, #500, then 12micron and 5 micron
                    aluminum oxide, we make a pitch lap with Gugolz pitch. The pitch is poured onto a
                    warmed tool, and after 3-5 minutes, the paper dam is stripped off, and a wood paint
                    stirrer that has been soaking in water is used to channel the tool, and a warm mirror
                    used to shape the pitch to the mirror curve.
                </p>

                <p>
                    Polishing takes from 4 to 8 hours using Cerium Oxide. We finish with a half hour
                    of red rouge, which gives an excellent surface finish, and provides gentle polishing
                    action for the figuring of the parabola. The mounts are standard Dobsonian design,
                    with most of the gotcha's worked out over the years. The completed scopes end up
                    costing about $350, but this includes two eyepieces, a Telrad Finder, rack and
                    pinion focuser, four vane spider, and enhanced coating secondary mirror. We make the
                    mirror cells, and the rest of the mount. The mirrors are coated at QSP in Santa Ana, CA,
                    with whatever coating the "grit pusher" prefers. And then......first light!
                </p>

                <p>
                    I must extend my congratulations to each ATM who has demonstrated the perseverance to
                    complete their telescope. We have had folks with all kinds of backgrounds, including
                    mechanics, liquor store operators, astrophysicists, students, store clerks....and
                    all ages, from a sixth grader to senior citizens. I would also like to thank Jim
                    Nunes and his family, who have provided the facility at their home in Sunol, which
                    has made the workshop possible. Also the support of Orion telescopes in providing a
                    discount on their ATM supplies, QSP for their rapid, high quality coating services,
                    and the Tri-Valley Stargazers Astronomy Club for their encouragement with this project.
                </p>

