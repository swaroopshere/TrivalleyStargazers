                <h2 class="subtitle">Types of Telescopes</h2>

                <p>
                    There are many types of telescopes out there. Here's a quick run down of the major
                    types you'll see for sale at your local telescope store.
                </p>

                <p>
                    <strong>Refractors</strong><br>
                    Refractors are what most people visualize when you say the word
                    "telescope". They use glass lenses.
                </p>

                <p>
                    <strong>Reflectors</strong><br>
                    Reflectors come in several configurations. They use mirrors.
                </p>

                <p>
                    <strong>Schmidt-Cassegrain (SCT)</strong><br>
                    SCTs are reflectors that use both a mirror and a lens (of sorts).
                </p>

                <p>
                    <strong>Maksutov (Mak)</strong><br>
                    Maks look similar to SCTs.
                </p>

