<h1 class="title">Observing Techniques</h1>

<p>
    Seeing and Transparency are values that an observer uses to compare the quality of the sky from night
    to night. The values are very specific to an individual observer's visual acuity. Seeing is a measure of
    how stable the sky is. Transparency is a measure of how clear the sky is. Most of the Astronomical
    League's Observing Programs require the observer to evaluate these conditions for each observation
    and to record them in their observation log.
</p>

<p>
    Here are two scales that are acceptable for all Observing Programs. They are simple to use and require
    no special equipment. Both of these values can be done very formally using special equipment, but for
    the TVS Observing Programs this level of effort is not required.
</p>

<h2 class="subtitle">Seeing: How Stable is the sky?</h2>
<ul>
    <li>E (excellent) - The brighter stars are not twinkling at all</li>
    <li>VG (very good) - The stars are twinkling slightly, but the brighter planets are not twinkling</li>
    <li>G (good) - The brighter planets are twinkling slightly</li>
    <li>F (fair) - The brighter planets are obviously twinkling</li>
    <li>P (poor) - The atmosphere is turbulent. All objects are twinkling to the point where observation is not practical</li>
</ul>

<h2 class="subtitle">Transparency: How clear is the sky?</h2>
<p>
    Transparency is a measure of what you can see in the nighttime sky in spite of dust, smoke, haze,
    humidity, or light pollution. An easy way to measure this is to use the magnitude of the faintest star you
    can see. Ideally, this would be looking straight up at zenith. But, to make life simpler, you can use the
    Little Dipper (Ursa Minor) if you can see it. Here is the scale:
</p>
<ol>
    <li>If you can't see Polaris</li>
    <li>If you can only see Polaris</li>
    <li>If you can see the two stars on the end of the bowl of the Little Dipper (Kochab and Pherkad)</li>
    <li>If you can see any of the stars in the handle of the Little Dipper</li>
    <li>If you can see 6 of the 7 stars in the Little Dipper</li>
    <li>If you can see all 7 stars in the Little Dipper</li>
    <li>If you can see stars near the Little Dipper that are not part of the stick figure. (I envy your young eyes...)</li>
</ol>

<p>
    Although atmospheric extinction will vary from season to season, and from latitude to latitude, using the Little
    Dipper is a simple and reasonable solution.
</p>

